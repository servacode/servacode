import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { runTests } from '@vscode/test-electron';

/**
 * RUN THE SUITE INSIDE A REAL VS CODE.
 *
 * SPEC: Phase 6 closure §8.
 *
 * Downloads a real VS Code the first time, launches it with the extension under
 * `--extensionDevelopmentPath`, and runs `tests/vscode` inside the Extension Host.
 *
 * Two details that are load-bearing rather than incidental:
 *
 *   THE ENTRY POINT IS COMMONJS. VS Code loads `--extensionTestsPath` with `require`, and
 *   everything in this project is ESM. A `.cjs` shim that dynamically imports the real
 *   entry point is the whole of the bridge, and it is generated here rather than checked in
 *   so it cannot drift from the output layout it points into.
 *
 *   THE WINDOW OPENS ON AN EMPTY FOLDER. A suite that ran with a project already open could
 *   not tell you whether the extension activates on a fresh machine — which is the state
 *   every owner starts in, and the state `Serva: New Project` and `Restore` exist for.
 */

const root = process.cwd();
const OUT = join(root, 'out', 'vscode-test');
const WORKSPACE = join(root, 'out', 'vscode-test-workspace');

/* ------------------------------------------------------------------------- compile */

rmSync(OUT, { recursive: true, force: true });
console.log('vscode-test: compiling the host suite');
execFileSync(
  process.execPath,
  [join(root, 'node_modules', 'typescript', 'lib', 'tsc.js'), '-p', 'tests/vscode/tsconfig.json'],
  { cwd: root, stdio: ['ignore', 'inherit', 'inherit'] },
);

/*
 * The compiled suite is ESM. Node decides that from the nearest package.json, and the repo
 * root's would be shadowed by nothing here — but writing it explicitly means the output
 * directory carries its own answer rather than inheriting one that could change.
 */
mkdirSync(join(OUT, 'tests', 'vscode'), { recursive: true });
writeFileSync(
  join(OUT, 'package.json'),
  JSON.stringify({ type: 'module' }, null, 2) + '\n',
  'utf8',
);

const shim = join(OUT, 'run.cjs');
writeFileSync(
  shim,
  [
    '/* Generated by scripts/run-vscode-tests.mjs. VS Code requires this entry point with',
    '   `require`, and the suite it starts is ESM; this is the bridge between the two. */',
    "const { pathToFileURL } = require('node:url');",
    "const { join } = require('node:path');",
    'module.exports.run = async function run() {',
    "  const entry = join(__dirname, 'tests', 'vscode', 'index.js');",
    '  const module = await import(pathToFileURL(entry).href);',
    '  return module.run();',
    '};',
    '',
  ].join('\n'),
  'utf8',
);

/* ------------------------------------------------------------------------- the extension */

console.log('vscode-test: building the extension');
execFileSync(
  process.execPath,
  [join(root, 'node_modules', 'typescript', 'lib', 'tsc.js'), '-p', 'extension/tsconfig.json'],
  { cwd: root, stdio: ['ignore', 'inherit', 'inherit'] },
);
/*
 * The compiled extension needs the generated catalogues beside it, and `tsc` emits only
 * TypeScript. Missing them is not a build error — it is an ACTIVATION error on a real
 * machine, which is exactly the class of defect this suite exists to catch.
 */
execFileSync(process.execPath, [join(root, 'scripts', 'copy-assets.mjs')], {
  cwd: root,
  stdio: ['ignore', 'inherit', 'inherit'],
});

/*
 * An empty folder, recreated each run. A suite that inherited whatever the last run left
 * behind would pass or fail for reasons nobody could see in the source.
 */
rmSync(WORKSPACE, { recursive: true, force: true });
mkdirSync(WORKSPACE, { recursive: true });

/* ------------------------------------------------------------------------- run */

/*
 * `ELECTRON_RUN_AS_NODE` MUST NOT REACH THE CHILD.
 *
 * When this command is started from a terminal inside VS Code, that variable is already set
 * in the environment — and a child `Code.exe` that inherits it starts as bare Node and
 * rejects every VS Code option it is given, including the ones @vscode/test-electron adds
 * itself. The failure reads as fifteen lines of `bad option:` and looks like a broken
 * harness rather than a poisoned environment.
 *
 * Deleted from this process rather than overridden in `extensionTestsEnv`, because the
 * launcher spreads `process.env` underneath whatever is passed there, and an override to
 * `undefined` survives that spread as the string "undefined".
 */
delete process.env.ELECTRON_RUN_AS_NODE;

try {
  await runTests({
    extensionDevelopmentPath: resolve(root, 'extension'),
    extensionTestsPath: shim,
    launchArgs: [
      /*
       * `--folder-uri`, not a bare path. A positional argument reaches Electron before it has
       * decided it is running as VS Code, and it tries to `require` it as a main module — the
       * suite then fails with `Cannot find module <your workspace>`, which reads like a
       * broken test and is actually a broken launch.
       */
      '--folder-uri=' + pathToFileURL(WORKSPACE).href,
      '--disable-extensions',
      '--disable-gpu',
      '--disable-workspace-trust',
      '--user-data-dir=' + join(root, 'out', 'vscode-user-data'),
    ],
    extensionTestsEnv: { SERVA_REPO_ROOT: root },
  });
  console.log('vscode-test: the Extension Host suite passed');
} catch (e) {
  console.error('vscode-test: the Extension Host suite failed');
  console.error(e instanceof Error ? e.message : String(e));
  process.exitCode = 1;
}
