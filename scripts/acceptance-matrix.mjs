import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * THE SERVA CODE 1.0 ACCEPTANCE MATRIX.
 *
 * SPEC: Phase 6 closure §2, §16.
 *
 * The previous generator marked a row COVERED when an implementation file and an evidence
 * file both existed. An independent audit called that coverage-by-presence, and it was
 * right: the comment claimed it proved the named test contained the assertion, and it proved
 * no such thing. It also listed thirty-three rows while omitting most of what Phase 6
 * required, so 33/33 was a complete score over an incomplete list.
 *
 * This one generates nothing of its own. It renders `acceptanceStatus`, which resolves typed
 * proofs against the repository, the file digests and the runs they cite. The matrix is an
 * INDEX INTO EVIDENCE, not evidence — and a requirement with no resolvable proof reports
 * NOT_VERIFIED, so the total falls.
 */

const root = process.cwd();
const { acceptanceStatus } = await import('../dist/acceptance/status.js');
const status = acceptanceStatus({ root });

const rows = status.requirements.map((r) => ({
  id: r.id,
  requirement: r.requirement,
  expects: r.expects,
  state: r.state,
  mandatory: r.mandatory,
  implementation: r.implementation ?? null,
  proof: r.resolution.source,
  refusals: r.resolution.refusals,
  ...(r.limitation === undefined ? {} : { limitation: r.limitation }),
}));

const proven = rows.filter((r) => r.state === 'PASS');
const unproven = rows.filter((r) => r.state !== 'PASS');

const matrix = {
  generatedFrom: 'scripts/acceptance-matrix.mjs',
  servaVersion: status.servaVersion,
  repository: status.repository ?? null,
  lines: status.lines.map((l) => ({ label: l.label, state: l.state, detail: l.detail })),
  rows,
  summary: {
    total: rows.length,
    proven: proven.length,
    notProven: unproven.map((r) => r.id),
    readyForOwnerUse: status.readyForOwnerUse,
  },
};

writeFileSync(
  join(root, 'evidence', 'ACCEPTANCE_MATRIX.json'),
  JSON.stringify(matrix, null, 2) + '\n',
  'utf8',
);

const md = [
  '# SERVA CODE 1.0 — ACCEPTANCE MATRIX',
  '',
  'Generated by `scripts/acceptance-matrix.mjs`, which renders `serva acceptance`. Every row',
  'resolves a TYPED PROOF against the repository: the exact commit and git tree, the digest of',
  'every file it cites, and — for a judged or live proof — a real AgentRun that has to resolve',
  'in a real store. A requirement with no resolvable proof reports NOT_VERIFIED and the total',
  'falls.',
  '',
  'This file is an index into evidence. It is not evidence.',
  '',
  '| | |',
  '|---|---|',
  '| Serva version | ' + status.servaVersion + ' |',
  '| Commit | ' + (status.repository?.commit ?? '(git identity unavailable)') + ' |',
  '| Tree | ' + (status.repository?.tree ?? '(git identity unavailable)') + ' |',
  '| Requirements proven | ' + String(proven.length) + '/' + String(rows.length) + ' |',
  '| Ready for owner use | ' + (status.readyForOwnerUse ? 'YES' : 'NO') + ' |',
  '',
  '## Verification types',
  '',
  '- **DETERMINISTIC** — an offline test asserts it, every run, with no model and no network.',
  '- **JUDGED** — a governed agent judged it, in a run the proof resolves.',
  '- **LIVE** — proved against the real provider, on a named machine, with the run resolved.',
  '- **HUMAN** — proved by a person following a written step, with output captured.',
  '- **SIMULATED** — proved in an isolated stand-in, and labelled as not device proof.',
  '',
  '## Lines',
  '',
  '| Line | State | Detail |',
  '|---|---|---|',
  ...status.lines.map((l) => '| ' + l.label + ' | ' + l.state + ' | ' + l.detail + ' |'),
  '',
  '## Requirements',
  '',
  '| ID | Requirement | Needs | Proof | State |',
  '|---|---|---|---|---|',
  ...rows.map(
    (r) =>
      '| ' +
      r.id +
      ' | ' +
      r.requirement +
      ' | ' +
      r.expects +
      ' | `' +
      r.proof +
      '` | ' +
      r.state +
      ' |',
  ),
  '',
  '## Why each unproven requirement did not resolve',
  '',
  ...(unproven.length === 0
    ? ['Every requirement resolved.']
    : unproven.map((r) => '- **' + r.id + '** — ' + (r.refusals[0] ?? 'no proof'))),
  '',
  '## Stated limitations',
  '',
  ...(rows.filter((r) => r.limitation !== undefined).length === 0
    ? ['None recorded.']
    : rows
        .filter((r) => r.limitation !== undefined)
        .map((r) => '- **' + r.id + '** — ' + r.limitation)),
].join('\n');

writeFileSync(join(root, 'evidence', 'ACCEPTANCE_MATRIX.md'), md + '\n', 'utf8');

console.log(
  'acceptance matrix: ' +
    String(proven.length) +
    '/' +
    String(rows.length) +
    ' requirements proven; ready=' +
    String(status.readyForOwnerUse),
);
if (!status.readyForOwnerUse) {
  console.log('not proven: ' + matrix.summary.notProven.join(', '));
  process.exitCode = 1;
}
