import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';
import {
  downloadAndUnzipVSCode,
  resolveCliArgsFromVSCodeExecutablePath,
  runTests,
} from '@vscode/test-electron';

/**
 * THE EXTENSION AN OWNER INSTALLS, INSTALLED THE WAY AN OWNER INSTALLS IT.
 *
 * SPEC: Phase 6 closure §8, §12; the 1.0.1 packaging audit.
 *
 * `run-vscode-tests.mjs` launches the Extension Host with
 *
 *   --extensionDevelopmentPath D:/SEVACODE/extension
 *
 * which means the extension under test sits inside the repository, one directory below
 * `D:/SEVACODE/node_modules`. Node's resolver walks upward, finds `zod` there, and the suite
 * passes. It passed for the whole of 1.0.0 while the extension declared no runtime dependency
 * at all and failed on its first import anywhere else.
 *
 * That suite is not wrong — it tests behaviour inside a real editor, which is worth testing.
 * It simply cannot answer the packaging question, because it runs in the one place where the
 * answer is always yes.
 *
 * So this asks the question somewhere the repository cannot help:
 *
 *   the VSIX is installed with `code --install-extension` into an extensions directory that
 *   contains nothing else;
 *
 *   the Extension Host runs against THAT installation — no `extensionDevelopmentPath`, no
 *   `--disable-extensions`, and a user-data directory made fresh for the run;
 *
 *   the smoke test activates the extension by id and asks it to do something.
 *
 * If `zod` were missing from the VSIX, activation would throw here and nowhere else.
 */

const root = process.cwd();
const vsix = process.argv[2] ?? join(root, 'release', 'serva-code-1.0.1.vsix');

if (!existsSync(vsix)) {
  console.error('validate-vsix: no VSIX at ' + vsix);
  console.error('  run `npm run package:extension` first.');
  process.exit(1);
}

/* Everything the editor writes goes somewhere disposable, so the run starts from nothing. */
const sandbox = mkdtempSync(join(tmpdir(), 'serva-vsix-'));
const extensionsDir = join(sandbox, 'extensions');
const userDataDir = join(sandbox, 'user-data');
const workspace = join(sandbox, 'workspace');
for (const d of [extensionsDir, userDataDir, workspace]) mkdirSync(d, { recursive: true });

console.log('validate-vsix: ' + vsix);
console.log('  sandbox ' + sandbox);

const vscodeExecutablePath = await downloadAndUnzipVSCode();
/*
 * Only the CLI path. `resolveCliArgsFromVSCodeExecutablePath` also returns default
 * `--extensions-dir` and `--user-data-dir` pointing INTO `D:/SEVACODE/.vscode-test`, and
 * accepting those would install into the repository — which is the isolation this script
 * exists to establish.
 */
const [cli] = resolveCliArgsFromVSCodeExecutablePath(vscodeExecutablePath);

/* ------------------------------------------------------------------ install the VSIX */

console.log('  installing the VSIX into an empty extensions directory');
const installed = execFileSync(
  String(cli),
  [
    '--install-extension',
    vsix,
    '--extensions-dir',
    extensionsDir,
    '--user-data-dir',
    userDataDir,
    '--force',
  ],
  {
    encoding: 'utf8',
    timeout: 10 * 60_000,
    stdio: ['ignore', 'pipe', 'pipe'],
    /* The VS Code CLI is a `.cmd` on Windows, which Node will not spawn directly. */
    shell: process.platform === 'win32',
  },
);
console.log('    ' + installed.trim().split(/\r?\n/).slice(-1)[0]);

/* ------------------------------------------------------------------ the smoke suite */

const out = join(sandbox, 'suite');
mkdirSync(out, { recursive: true });

/*
 * Written here rather than compiled from `tests/vscode`, because this suite must not import
 * anything from the repository — that is the whole point. It is CommonJS because VS Code
 * `require`s the test entry point, and it touches only the `vscode` API.
 */
writeFileSync(
  join(out, 'run.cjs'),
  `
/* Generated by scripts/validate-vsix.mjs. Deliberately self-contained: it imports nothing
   from D:/SEVACODE, so a pass here is a statement about the VSIX and not about the repo. */
const assert = require('node:assert');
const vscode = require('vscode');

const EXTENSION_ID = 'serva.serva-code';

module.exports.run = async function run() {
  const ext = vscode.extensions.getExtension(EXTENSION_ID);
  assert.ok(ext, EXTENSION_ID + ' is not installed in this editor');

  /* Activation is where a missing runtime dependency surfaces, and it throws rather than
     returning a flag — which is exactly the failure this script exists to catch. */
  await ext.activate();
  assert.strictEqual(ext.isActive, true, EXTENSION_ID + ' did not activate');

  const version = ext.packageJSON.version;
  assert.ok(version, 'the installed extension reports no version');

  /* Activated is not the same as working. A contributed command that is not registered means
     the activation function returned before finishing. */
  const commands = await vscode.commands.getCommands(true);
  const contributed = (ext.packageJSON.contributes && ext.packageJSON.contributes.commands) || [];
  assert.ok(contributed.length > 0, 'the extension contributes no commands');

  const missing = contributed.map((c) => c.command).filter((c) => !commands.includes(c));
  assert.deepStrictEqual(missing, [], 'contributed commands never registered: ' + missing.join(', '));

  console.log('  activated ' + EXTENSION_ID + ' ' + version);
  console.log('  ' + contributed.length + ' contributed command(s), all registered');
};
`,
  'utf8',
);

/* ------------------------------------------------------------------ run against it */

/*
 * `ELECTRON_RUN_AS_NODE` leaks in from the parent and makes the launcher start Node instead of
 * the editor. The same removal `run-vscode-tests.mjs` documents, for the same reason.
 */
delete process.env.ELECTRON_RUN_AS_NODE;

let failed = false;
try {
  await runTests({
    vscodeExecutablePath,
    /*
     * No `extensionDevelopmentPath`. The extension under test is the one installed above, and
     * `--disable-extensions` is absent because disabling extensions would disable it.
     */
    extensionTestsPath: join(out, 'run.cjs'),
    launchArgs: [
      '--folder-uri=' + pathToFileURL(workspace).href,
      '--extensions-dir=' + extensionsDir,
      '--user-data-dir=' + userDataDir,
      '--disable-gpu',
      '--disable-workspace-trust',
    ],
  });
  console.log('');
  console.log('validate-vsix: the installed extension activated and registered its commands');
} catch (e) {
  failed = true;
  console.error('');
  console.error('validate-vsix: the installed extension FAILED');
  console.error(e instanceof Error ? e.message : String(e));
}

rmSync(sandbox, { recursive: true, force: true });
if (failed) process.exitCode = 1;
