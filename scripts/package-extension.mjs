import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * BUILD THE VSIX AN OWNER INSTALLS, WITH NOTHING ASSUMED ABOUT THE MACHINE.
 *
 * SPEC: Phase 6 closure §12; the 1.0.1 packaging audit.
 *
 * Serva Code 1.0.0 shipped no way to produce an installable extension. There was an Extension
 * Host test suite, and it passed — because `--extensionDevelopmentPath` points at
 * `D:/SEVACODE/extension`, where the repository's own `node_modules` is one directory up and
 * Node resolves `zod` without anyone declaring it. The extension had never been proven to work
 * anywhere else, and outside the repository it failed on its first import.
 *
 * So this does the two things that gap needs:
 *
 *   the extension's production dependencies are installed INTO `extension/node_modules` from
 *   its own lockfile, so the VSIX carries what it imports rather than borrowing it;
 *
 *   `@vscode/vsce` is a devDependency of this repository and run through `npx --no-install`,
 *   so building a release never depends on what happens to be on a developer's PATH.
 *
 * The result is written to `release/` with its SHA-256, because an artifact an owner downloads
 * needs something they can check it against.
 */

const repoRoot = process.cwd();
const extensionDir = join(repoRoot, 'extension');
const releaseDir = join(repoRoot, 'release');

function run(cmd, args, cwd) {
  return execFileSync(cmd, args, {
    cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
    timeout: 15 * 60_000,
    shell: process.platform === 'win32',
  });
}

const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';

const manifest = JSON.parse(readFileSync(join(extensionDir, 'package.json'), 'utf8'));
console.log('package-extension: ' + manifest.name + ' ' + manifest.version);

/* 1. Compile. The VSIX carries compiled output, never TypeScript. */
console.log('  building the extension');
run(npm, ['run', 'build:extension'], repoRoot);

/*
 * 2. The extension's OWN production dependencies.
 *
 * `--omit=dev` because a VSIX carrying `@types/vscode` would ship a compiler's opinion to an
 * owner. `npm ci` rather than `install` so the lockfile decides and two builds agree.
 */
console.log('  installing production dependencies from extension/package-lock.json');
run(npm, ['ci', '--omit=dev', '--no-audit', '--no-fund'], extensionDir);

/*
 * 3. Keep out of the VSIX what an owner has no use for.
 *
 * Written rather than assumed: with no `.vscodeignore`, vsce packages the whole directory
 * including source maps and type declarations. They are harmless but they are not the product.
 */
const ignore = [
  '# Generated by scripts/package-extension.mjs — the VSIX carries what runs, and nothing else.',
  '**/*.map',
  '**/*.ts',
  '!**/*.d.ts',
  '**/tsconfig.json',
  'package-lock.json',
  '.vscode/**',
  '',
].join('\n');
writeFileSync(join(extensionDir, '.vscodeignore'), ignore, 'utf8');

/* 4. Package. */
mkdirSync(releaseDir, { recursive: true });
const vsixName = manifest.name + '-' + manifest.version + '.vsix';
const vsixPath = join(releaseDir, vsixName);
rmSync(vsixPath, { force: true });

console.log('  packaging with @vscode/vsce');
run(
  'npx',
  [
    '--no-install',
    'vsce',
    'package',
    '--out',
    vsixPath,
    /* This extension is private to its owner and has no repository field or README badge. */
    '--allow-missing-repository',
    '--skip-license',
  ],
  extensionDir,
);

if (!existsSync(vsixPath)) {
  console.error('package-extension: vsce reported success but produced no file at ' + vsixPath);
  process.exit(1);
}

const bytes = readFileSync(vsixPath);
const digest = createHash('sha256').update(bytes).digest('hex');

console.log('');
console.log('  ' + vsixName);
console.log('  ' + String(bytes.length) + ' bytes');
console.log('  sha256 ' + digest);

/*
 * 5. Say what is in it, because "vsce reported success" is the claim this whole audit exists
 * to distrust. A VSIX missing its runtime dependency installs perfectly and fails on activation.
 */
const listing = run('npx', ['--no-install', 'vsce', 'ls', '--tree'], extensionDir);
const carriesZod = /node_modules[\\/]zod/.test(listing) || listing.includes('zod');
console.log('  zod inside the VSIX: ' + (carriesZod ? 'yes' : 'NO'));

if (!carriesZod) {
  console.error('');
  console.error('package-extension: the extension imports zod and the VSIX does not carry it.');
  console.error('  An owner installing this would get ERR_MODULE_NOT_FOUND on activation.');
  process.exit(1);
}

writeFileSync(join(releaseDir, vsixName + '.sha256'), digest + '  ' + vsixName + '\n', 'utf8');

void readdirSync;
console.log('');
console.log('package-extension: wrote release/' + vsixName);
