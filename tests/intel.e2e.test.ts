/**
 * SCENARIO A — NEW PRODUCT, END TO END.
 *
 * Owner idea → every governed department → gates → readiness → Phase 4 work items.
 *
 * Deterministic: a scripted engine and a fake retriever. No network, no model spend. What
 * is proved is that the COMPANY runs — 26 departments, each its own run, each writing its
 * own canon — and that the thing handed to Phase 4 is derived from accepted truth rather
 * than asserted by anybody.
 */

const roots: string[] = [];
const fixtures: string[] = [];
afterEach(() => {
  for (const r of roots.splice(0)) cleanup(r);
  for (const f of fixtures.splice(0)) removeFixtureDir(f);
  configureResearchSeeds({ hosts: [], urls: [] });
});

const WORK_ITEM = 'SC-WI-000700';

function setup() {
  const { store, root, deps } = freshStore();
  roots.push(root);
  const engine = new FakeEngineAdapter({ clock: deps.clock });
  for (const [agentId, output] of E2E_SCRIPT) {
    engine.script(agentId, { structuredOutput: output });
  }
  const intel = {
    store,
    clock: deps.clock,
    ids: deps.ids,
    /* Ids generated by earlier departments are substituted into later scripted payloads. */
    engine: resolvingEngine(engine, store),
    projectRoot: root,
    gateway: {
      store,
      clock: deps.clock,
      ids: deps.ids,
      retriever: seedRetriever(),
    },
  };
  configureResearchSeeds({ hosts: ['example.com'], urls: ['https://example.com/rival-a'] });
  return { store, root, deps, engine, intel };
}

describe('the whole company runs', () => {
  it('takes an idea through every department to an engineering handoff', async () => {
    const f = setup();
    recordIdea(f.intel, 'I want an app so my bakery stops losing phone orders in the morning.');

    const orchestrator = intelligenceOrchestrator(f.intel, WORK_ITEM, 'PRF-NEW-PRODUCT');
    const result = await orchestrator.advance();

    /* --- every department ran as its own governed run --- */
    const agents = result.ran.map((r) => r.agentId);
    const where =
      'state=' +
      result.state +
      ' halted=' +
      (result.record.haltedAtStage ?? '-') +
      ' reason=' +
      (result.reason ?? '-') +
      ' ran=' +
      result.ran.map((r) => r.agentId + ':' + r.outcome).join(',');
    for (const expected of [
      'SC-AGENT-020', // intake + product validation
      'SC-AGENT-030', // discovery
      'SC-AGENT-040', // business analysis
      'SC-AGENT-050', // requirements
      'SC-AGENT-051', // NFRs
      'SC-AGENT-052', // independent requirements verifier
      'SC-AGENT-060', // market research
      'SC-AGENT-063', // independent source verifier
      'SC-AGENT-061', // competitive analyst
      'SC-AGENT-062', // innovation strategist
      'SC-AGENT-110', // cost
      'SC-AGENT-070', // architect
      'SC-AGENT-072', // independent architecture reviewer
      'SC-AGENT-100', // infrastructure
      'SC-AGENT-080', // data architect
      'SC-AGENT-082', // independent data reviewer
      'SC-AGENT-090', // security architect
      'SC-AGENT-071', // technology evaluator
      'SC-AGENT-120', // UX
      'SC-AGENT-123', // independent UX reviewer
      'SC-AGENT-130', // design system
      'SC-AGENT-131', // UI composition
      'SC-AGENT-133', // independent design reviewer
      'SC-AGENT-140', // admin operability
      'SC-AGENT-210', // test design
    ]) {
      expect(agents, 'department did not run: ' + expected + ' | ' + where).toContain(expected);
    }
    expect(
      result.state,
      'halted at ' + (result.record.haltedAtStage ?? '?') + ': ' + (result.reason ?? ''),
    ).toBe(OrchestratorState.COMPLETE);

    /* --- risk was COMPUTED, with no model call --- */
    const riskRun = result.ran.find((r) => r.departmentId === 'DEPT-RISK');
    expect(riskRun?.runId).toBeUndefined();
    const risks = repository(f.store, ARTIFACT_TYPES.RISK, RiskSchema).list();
    expect(risks.length).toBeGreaterThan(0);
    // UNKNOWN is preserved, never rounded down to LOW.
    expect(risks.some((r) => r.severity === 'UNKNOWN')).toBe(true);

    /* --- the gates ran as control flow, in order, and accepted --- */
    const gates = readGateResults(f.store);
    for (const gateId of [
      'SC-GATE-INTAKE',
      'SC-GATE-DISCOVERY',
      'SC-GATE-PRODUCT_VALIDATION',
      'SC-GATE-REQUIREMENTS',
      'SC-GATE-COMPETITIVE',
    ]) {
      const g = gates.find((x) => x.gateRef === gateId);
      expect(g, gateId + ' was never evaluated').toBeDefined();
      expect([GateVerdict.PASS, GateVerdict.PASS_WITH_QUALIFICATION]).toContain(g?.verdict);
    }

    /* --- §8: the traceability chain actually chains --- */
    const features = repository(f.store, ARTIFACT_TYPES.FEATURE, FeatureSchema).list();
    const requirements = repository(f.store, ARTIFACT_TYPES.REQUIREMENT, RequirementSchema).list();
    const reviews = repository(
      f.store,
      ARTIFACT_TYPES.ADMIN_OPERABILITY_REVIEW,
      AdminOperabilityReviewSchema,
    ).list();

    expect(features.length).toBeGreaterThan(0);
    for (const feature of features) {
      // Requirement → Feature
      expect(requirements.some((r) => r.tracesTo.some((t) => t.id === feature.id))).toBe(true);
      // Feature → AdminOperabilityReview, for EVERY feature (§27)
      expect(reviews.some((r) => r.featureRef.id === feature.id)).toBe(true);
    }
    // Requirement → Flow → Screen
    expect(f.store.listCanonIds(ARTIFACT_TYPES.FLOW).length).toBeGreaterThan(0);
    expect(f.store.listCanonIds(ARTIFACT_TYPES.SCREEN_COMPOSITION).length).toBeGreaterThan(0);
    // Requirement → TestCase
    expect(f.store.listCanonIds(ARTIFACT_TYPES.TEST_CASE).length).toBeGreaterThan(0);

    /* --- the ledger describes the whole lifecycle --- */
    const ledger = readLedger(f.store, WORK_ITEM);
    expect(new Set(ledger.map((e) => e.stageId)).size).toBeGreaterThanOrEqual(16);
  }, 180_000);

  it('readiness is DERIVED from the Store, with nothing handed to it', async () => {
    const f = setup();
    recordIdea(f.intel, 'bakery order capture');
    await intelligenceOrchestrator(f.intel, WORK_ITEM, 'PRF-NEW-PRODUCT').advance();

    /*
     * NOTHING IS INJECTED. This is the production call, exactly as the CLI makes it.
     *
     * The previous version of this test passed a set of completed review criteria and
     * then asserted READY — which proved only that readiness believes what it is told.
     * The reviews are now reconstructed from immutable gate evidence, so a caller has
     * nothing to contribute and no way to contribute it.
     */
    const ready = assessReadiness({
      store: f.store,
      clock: f.deps.clock,
      ids: f.deps.ids,
      workItemId: WORK_ITEM,
    });
    expect(ready.blockers, ready.blockers.join(' | ')).toEqual([]);
    expect(ready.status).toBe('READY');

    /* --- and the evidence it read is real, attributable and independent --- */
    const evaluations = readCriterionEvaluations(f.store);
    for (const [criterion, reviewer] of [
      ['RQ-4', 'SC-AGENT-052'],
      ['AR-2', 'SC-AGENT-072'],
      ['DA-1', 'SC-AGENT-082'],
      ['UX-2', 'SC-AGENT-123'],
      ['DS-1', 'SC-AGENT-133'],
    ] as const) {
      const matching = evaluations.filter((e) => e.criterionRef === criterion);
      const latest = matching[matching.length - 1];
      expect(latest, criterion + ' was never evaluated').toBeDefined();
      expect(latest?.basis).toBe('JUDGED');
      expect(latest?.judgedBy?.role).toBe(reviewer);
      expect(latest?.value).toBe('MET');
      /* It names what it judged, at the version it judged. */
      expect(latest?.artifactVersionsEvaluated.length).toBeGreaterThan(0);
    }

    /* The package is REFERENCES into canon, with versions pinned. */
    expect(
      ready.package.refs.requirementBaseline ?? ready.package.refs.nfrs.length > 0,
    ).toBeTruthy();
    expect(ready.package.refs.adminOperability.length).toBeGreaterThan(0);
    expect(ready.package.refs.testStrategy.length).toBeGreaterThan(0);
    for (const ref of ready.package.refs.nfrs) expect(ref.version).toBeGreaterThan(0);
    // Nothing was copied: the package holds no requirement text of its own.
    expect(JSON.stringify(ready.package.refs)).not.toContain('shall');
  }, 180_000);

  it('a review stops counting once the thing it reviewed changes', async () => {
    const f = setup();
    recordIdea(f.intel, 'bakery order capture');
    await intelligenceOrchestrator(f.intel, WORK_ITEM, 'PRF-NEW-PRODUCT').advance();
    expect(
      assessReadiness({
        store: f.store,
        clock: f.deps.clock,
        ids: f.deps.ids,
        workItemId: WORK_ITEM,
      }).status,
    ).toBe('READY');

    /*
     * Rewrite the data model. Nobody has reviewed THIS version — SC-AGENT-082 accepted
     * the one before it — and a review that survives the artifact it reviewed is not a
     * review, it is a rubber stamp with a long memory.
     */
    const dataModels = repository(f.store, ARTIFACT_TYPES.DATA_MODEL, DataModelSchema).list();
    const model = dataModels[0];
    expect(model).toBeDefined();
    const tx = f.store.begin();
    repository(f.store, ARTIFACT_TYPES.DATA_MODEL, DataModelSchema).put(tx, {
      ...(model as NonNullable<typeof model>),
    });
    tx.commit();

    const after = assessReadiness({
      store: f.store,
      clock: f.deps.clock,
      ids: f.deps.ids,
      workItemId: WORK_ITEM,
    });
    expect(after.status).not.toBe('READY');
    expect(after.blockers.join(' | ')).toContain('DA-1');
    expect(after.blockers.join(' | ')).toContain('has since changed');
  }, 180_000);

  it('an unanswered owner decision makes READY unreachable', async () => {
    const f = setup();
    recordIdea(f.intel, 'bakery order capture');
    await intelligenceOrchestrator(f.intel, WORK_ITEM, 'PRF-NEW-PRODUCT').advance();

    /* Raise one after the fact, as a later change request would. */
    const tx = f.store.begin();
    const { OwnerDecisionRequestSchema } =
      await import('../src/intelligence/artifacts/governance.js');
    repository(f.store, ARTIFACT_TYPES.OWNER_DECISION_REQUEST, OwnerDecisionRequestSchema).put(tx, {
      id: f.deps.ids.next('SC-ODR'),
      createdAt: f.deps.clock.now(),
      question: 'Should the loyalty scheme apply to phone orders?',
      whyServaCannotDecide: 'It is a commercial policy.',
      purpose: 'BUSINESS_RULE',
      options: [
        { option: 'Yes', impact: 'phone orders earn points', disposition: 'APPROVE' },
        { option: 'No', impact: 'counter only', disposition: 'REJECT' },
      ],
      recommendation: 'Yes',
      recommendationRationale: 'consistency across channels',
      blocksWork: true,
      blockedRefs: [],
      state: 'OPEN',
      meta: {
        provenance: { marking: 'SYSTEM', component: 'test' },
        attribution: { at: f.deps.clock.now() },
      },
    } as never);
    tx.commit();

    const assessment = assessReadiness({
      store: f.store,
      clock: f.deps.clock,
      ids: f.deps.ids,
      workItemId: WORK_ITEM,
    });
    expect(assessment.status).toBe('BLOCKED');
    expect(assessment.blockers.join(' ')).toContain('owner decision is unanswered');

    /* ...and no engineering work can be generated from it. */
    expect(() =>
      generateWorkItems({
        store: f.store,
        workItemId: WORK_ITEM,
        clock: f.deps.clock,
        ids: f.deps.ids,
        baseCommit: 'a'.repeat(40),
      }),
    ).toThrow(/readiness is BLOCKED/);
  }, 180_000);
});

describe('Phase 5 satisfies the Phase 4 contract', () => {
  it('generates a work item the real Engineering Factory accepts', async () => {
    const f = setup();
    recordIdea(f.intel, 'bakery order capture');
    await intelligenceOrchestrator(f.intel, WORK_ITEM, 'PRF-NEW-PRODUCT').advance();

    const readiness = assessReadiness({
      store: f.store,
      clock: f.deps.clock,
      ids: f.deps.ids,
      workItemId: WORK_ITEM,
    });
    expect(readiness.status).toBe('READY');

    /* --- a real fixture repository, and the REAL factory --- */
    const repo = join(f.root, 'repo');
    mkdirSync(join(repo, 'src'), { recursive: true });
    writeFileSync(join(repo, 'src', 'total.js'), 'module.exports = 1;\n', 'utf8');
    const g = (...a: string[]): string =>
      execFileSync('git', a, { cwd: repo, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
    g('init', '-q', '-b', 'main');
    g('config', 'user.email', 'fx@localhost');
    g('config', 'user.name', 'Fixture');
    g('config', 'commit.gpgsign', 'false');
    g('add', '.');
    g('commit', '-q', '-m', 'base');
    const base = g('rev-parse', 'HEAD').trim();

    const handoff = generateWorkItems({
      store: f.store,
      workItemId: WORK_ITEM,
      clock: f.deps.clock,
      ids: f.deps.ids,
      baseCommit: base,
      allowedScope: ['src/'],
    });
    expect(handoff.items.length).toBeGreaterThan(0);

    const item = handoff.items[0];
    /* Engineering receives DECISIONS: canon ids travel with the work. */
    expect(item?.requirements.join(' ')).toMatch(/\[SC-REQ-/);
    expect(item?.requirements.join(' ')).toMatch(/\[SC-BR-/);
    expect(item?.requirements.join(' ')).toMatch(/\[SC-NFR-/);
    expect(item?.decisions.join(' ')).toMatch(/\[SC-ARCH-/);
    expect(item?.acceptanceCriteria.join(' ')).toMatch(/\[SC-AC-/);

    /* --- the REAL factory validates it. Phase 4 is not modified to fit. --- */
    const git = new GitService({ repoRoot: repo });
    const substrate = new SimulatedExecutionSubstrate({ clock: f.deps.clock, enforcement: 'HARD' });
    const fixture = makeFixtureDir();
    fixtures.push(fixture);
    const qualification = await substrate.qualify(fixture);

    const factory = new EngineeringFactory({
      store: f.store,
      git,
      workspaces: new EngineeringWorkspaceManager({
        store: f.store,
        git,
        clock: f.deps.clock,
        projectRoot: repo,
      }),
      recipes: new RecipeRegistry(),
      registry: ContractRegistry.shared(),
      qualification,
      executorDeps: {
        store: f.store,
        clock: f.deps.clock,
        ids: f.deps.ids,
        substrate,
        qualification,
        env: process.env,
      },
      gateDeps: { ids: f.deps.ids, clock: f.deps.clock, evaluator: 'E2E' },
      projectRoot: repo,
      enabledProducers: new Set(['SC-AGENT-150']),
      producerBoundary: qualification.boundary,
      allowSimulatedBoundary: true,
    });

    /*
     * The proof: Phase 4's own `recordWorkItem` accepts the generated item unchanged.
     * If this ever fails, the defect is Phase 5's — the factory contract does not bend.
     */
    const recorded = factory.recordWorkItem(item as never);
    expect(recorded.workItemId).toBe(item?.workItemId);
    expect(recorded.producerAgentId).toBe('SC-AGENT-150');
    expect(recorded.reviewerAgentId).toBe('SC-AGENT-200');
    expect(recorded.acceptanceCriteria.length).toBeGreaterThan(0);
  }, 180_000);
});
